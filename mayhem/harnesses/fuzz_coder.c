/*
 * libFuzzer harness for ruby-pg's type coders (PG::TextDecoder, PG::BinaryDecoder, PG::TextEncoder,
 * PG::BinaryEncoder, the COPY row coders and the record coder).
 *
 * The extension objects (the ext/ sources) are linked statically, so the harness embeds libruby, calls the
 * extension's own Init_pg_ext() and then drives the coders through their public Ruby API, exactly as
 * an application decodes data it received from a server. Which coders run is decided by a small Ruby
 * driver script per target (mayhem/harnesses/<target>.rb, prefixed by prelude.rb); build.sh embeds
 * that script into this file as FUZZ_SCRIPT (fuzz_script.h) so the binary reads no file at runtime.
 *
 * State kept across inputs: the Ruby VM and the PG module (read-only class definitions). The driver
 * builds fresh coder objects for every input, so no coder setting leaks from one input to the next.
 */
#include <ruby.h>
#include <signal.h>
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#include "fuzz_script.h" /* static const char FUZZ_SCRIPT[]; generated by mayhem/build.sh */

void Init_pg_ext(void);

static ID id_fuzz_one;

static VALUE init_ext(VALUE unused) {
  (void)unused;
  Init_pg_ext();
  return Qnil;
}

static VALUE call_fuzz_one(VALUE str) {
  /* fuzz_one is a private top-level method; rb_funcall ignores visibility. */
  return rb_funcall(Qnil, id_fuzz_one, 1, str);
}

static void die_with_ruby_error(const char *what) {
  VALUE msg = rb_funcall(rb_errinfo(), rb_intern("full_message"), 0);
  fprintf(stderr, "fuzz_coder: %s failed:\n%s\n", what, StringValueCStr(msg));
  abort();
}

int LLVMFuzzerInitialize(int *argc, char ***argv) {
  /* Ruby installs its own SIGSEGV/SIGBUS/... handlers (rb_bug reports); keep the sanitizer's. */
  static const int sigs[] = {SIGSEGV, SIGBUS, SIGILL, SIGFPE};
  struct sigaction saved[sizeof sigs / sizeof sigs[0]];
  for (size_t i = 0; i < sizeof sigs / sizeof sigs[0]; i++) sigaction(sigs[i], NULL, &saved[i]);

  ruby_sysinit(argc, argv);
  /* argc points into main()'s frame: the GC scans the stack from there down. */
  ruby_init_stack((void *)argc);
  ruby_init();
  /* Process an empty `-e` program: sets up the load path, encodings and rubygems (bigdecimal is a
   * bundled gem). The returned node is not run. */
  {
    char *opts[] = {(char *)"fuzz_coder", (char *)"-e", (char *)"", NULL};
    ruby_options(3, opts);
  }

  int state = 0;
  rb_protect(init_ext, Qnil, &state);
  if (state) die_with_ruby_error("Init_pg_ext");
  rb_eval_string_protect(FUZZ_SCRIPT, &state);
  if (state) die_with_ruby_error("loading the driver script");
  id_fuzz_one = rb_intern("fuzz_one");

  for (size_t i = 0; i < sizeof sigs / sizeof sigs[0]; i++) sigaction(sigs[i], &saved[i], NULL);
  return 0;
}

int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {
  int state = 0;
  VALUE str = rb_str_new((const char *)data, (long)size);
  rb_protect(call_fuzz_one, str, &state);
  /* The driver rescues every StandardError per coder call; anything else that escapes (e.g.
   * NoMemoryError for an absurd length) is a Ruby-level rejection, not a memory error. */
  if (state) {
    if (getenv("FUZZ_CODER_DEBUG")) {
      VALUE msg = rb_funcall(rb_errinfo(), rb_intern("full_message"), 0);
      fprintf(stderr, "fuzz_coder: escaped: %s\n", StringValueCStr(msg));
    }
    rb_set_errinfo(Qnil);
  }
  return 0;
}
